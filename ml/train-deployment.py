"""Train and export the radar's placement model from offline game simulations."""
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import mean_absolute_error
from sklearn.model_selection import GroupShuffleSplit
from sklearn.neural_network import MLPRegressor
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).resolve().parent


def main():
    with (HERE / "deployment.jsonl").open(encoding="utf-8") as source:
        examples = [json.loads(line) for line in source]

    features = np.array([row["features"] for row in examples])
    actual = np.array([row["leaked"] for row in examples])
    total = np.array([row["total"] for row in examples])
    groups = np.array([row["group"] for row in examples])
    baseline = np.array([row["baseline"] for row in examples])
    # Repeated starting layouts can have identical features under different seeds.
    _, layout_ids = np.unique(features[baseline].round(8), axis=0, return_inverse=True)
    layout_by_group = dict(zip(groups[baseline], layout_ids))
    layout_groups = [layout_by_group[group] for group in groups]
    splitter = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
    train, test = next(splitter.split(features, groups=layout_groups))

    scaler = StandardScaler().fit(features[train])
    model = MLPRegressor(
        hidden_layer_sizes=(64, 32), activation="relu", max_iter=100,
        random_state=42, batch_size=128, alpha=0.015, tol=0.00005,
    )
    model.fit(scaler.transform(features[train]), actual[train] / total[train])
    # Score and display the expected count even when adaptive composition changes wave size.
    predicted = np.clip(model.predict(scaler.transform(features[test])), 0, 1) * total[test]
    actual_test = actual[test]
    selections = []
    test_groups, test_baseline = groups[test], baseline[test]
    for group in np.unique(test_groups):
        indices = np.flatnonzero(test_groups == group)
        keep = indices[test_baseline[indices]][0]
        build = indices[~test_baseline[indices]]
        if not len(build):
            continue
        pick = build[np.argmin(predicted[build])]
        if predicted[pick] + 0.25 >= predicted[keep]:
            pick = keep
        selections.append([
            actual_test[keep], actual_test[pick], actual_test[build].mean(),
            actual_test[indices].min(),
        ])

    baseline_mean, advice_mean, random_mean, oracle_mean = np.array(selections).mean(axis=0)
    print(f"训练 {len(train)} / 留出 {len(test)} 次模拟 · 每次 {features.shape[1]} 个特征")
    print(f"留出集漏怪 MAE = {mean_absolute_error(actual_test, predicted):.3f} 只")
    print(f"{len(selections)} 个可买塔的留出布局 · 平均实际漏怪")
    print(f"保持原样 {baseline_mean:.3f} · MLP 策略 {advice_mean:.3f} · "
          f"随机买塔 {random_mean:.3f} · 采样内最优 {oracle_mean:.3f}")

    artifact = {
        "maxWave": int(features[train, 0].max()),
        "mean": scaler.mean_.tolist(),
        "scale": scaler.scale_.tolist(),
        "layers": [
            {"weights": weights.T.tolist(), "bias": bias.tolist()}
            for weights, bias in zip(model.coefs_, model.intercepts_)
        ],
    }
    output = HERE.parent / "deployment-model.js"
    output.write_text(
        "// Generated by ml/train-deployment.py.\nwindow.TDDeploymentModel = "
        + json.dumps(artifact, separators=(",", ":"), allow_nan=False) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
